export const supportedLanguages = ['en', 'es', 'fr', 'ar', 'hi'];

export function browserLanguage(languages = navigator.languages || [navigator.language]) {
  for (const locale of languages) {
    const language = String(locale || '').toLowerCase().split('-')[0];
    if (supportedLanguages.includes(language)) return language;
  }
  return 'en';
}

export function translate(language, key, values = {}) {
  const template = translations[language]?.[key] || translations.en[key] || key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''));
}

export function translateAchievement(language, id, part, fallback) {
  const index = part === 'title' ? 0 : 1;
  return achievementContent[language]?.[id]?.[index] || fallback;
}

export function textDirection(language) {
  return language === 'ar' ? 'rtl' : 'ltr';
}
